'''
문제 설명
세 자리 자연수 두 개를 입력받아 두 번째 수의 각 자릿수와 첫 번째 수를 곱한 결과,
그리고 두 수의 최종 곱을 출력하는 문제입니다.

입력 예시
472
385
두 번째 숫자 385를 자릿수별로 보면:
일의 자리: 5
십의 자리: 8
백의 자리: 3

출력 예시
2360
3776
1416
181720
각 줄의 의미는 다음과 같습니다.
472 x 5
472 x 8
472 x 3
472 x 385
'''

import sys
input = sys.stdin.readline

a = int(input())
# ---------- 숫자로 입력받기 ----------
# b = int(input())
# print(a * (b % 10))
# print(a * ((b // 10) % 10))
# print(a * (b // 100))
# print(a * b)
# ---------- 문자열로 입력받기 ----------
b = input()

for i in range(2, -1, -1):
    print(a * int(b[i]))

print(a * int(b))